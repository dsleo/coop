from coop.config import TrustLevel

SIZE_WEIGHTS = {"size:small": 30, "size:medium": 20, "size:large": 5}
ISSUE_URL_RE = re.compile(r"github\.com/([^/]+/[^/]+)/issues/(\d+)")
LABEL_HELP, LABEL_CLAIMED = "coop-help", "coop-claimed"
BUDGET_RE = re.compile(r"^budget:(\d+)(k?)$", re.I)  # per-issue override, e.g. budget:50k or budget:50000
LABELS = [
    (LABEL_HELP, "0E8A16", "Open for coop AI token help"),
    (LABEL_CLAIMED, "FBCA04", "Claimed by a coop contributor (set by coop)"),
    ("size:small", "C5DEF5", "coop: quick fix, picked first"),
    ("size:medium", "C5DEF5", "coop: medium task"),
    ("size:large", "C5DEF5", "coop: big task, picked last"),
    *((f"budget:{b}k", "BFD4F2", f"coop: spend at most {b}k tokens on this issue") for b in (25, 50, 100, 200)),
]


def issue_budget(labels: list[str], default: int) -> int:
    """A `budget:<N>[k]` label on the issue overrides the repo's default budget."""
    for lbl in labels:
        if m := BUDGET_RE.match(lbl):
            return int(m.group(1)) * (1000 if m.group(2) else 1)
    return default


class GhError(RuntimeError):
    pass


def run_gh(args: list[str], check: bool = True, cwd: str | None = None) -> str:
    proc = subprocess.run(["gh", *args], capture_output=True, text=True, cwd=cwd)
    if check and proc.returncode != 0:
        raise GhError(proc.stderr.strip() or f"gh {' '.join(args)} failed")
    return proc.stdout.strip()


def current_github_user() -> str:
    return run_gh(["api", "user", "--jq", ".login"])


def infer_current_repo() -> str:
    return run_gh(["repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"])


def has_push_access(repo: str) -> bool:
    return run_gh(["api", f"repos/{repo}", "--jq", ".permissions.push"], check=False) == "true"


@dataclass
class BoardRepoEntry:
    repo: str
    default_budget: int = 100_000


@dataclass
class CoopIssue:
    repo: str
    number: int
    title: str
    url: str
    body: str
    labels: list[str]
    assignees: list[str]
    author: str
    default_budget: int


# ---------------------------------------------------------------- board manifest
# repos.toml lives at the root of the shared board repo:  [[repos]] repo = "a/b"


def fetch_board_manifest(board_repo: str) -> tuple[dict[str, Any], str]:
    try:
        payload = json.loads(run_gh(["api", f"repos/{board_repo}/contents/repos.toml"]))
    except GhError as e:
        raise GhError(
            f"Cannot read repos.toml in {board_repo} ({e}). "
            "Does the repo exist, and have you accepted the invitation (`coop accept`)?"
        ) from e
    decoded = base64.b64decode(payload["content"]).decode("utf-8")
    return tomllib.loads(decoded), payload["sha"]


TOOL_REPO = "dsleo/coop"


def join_steps(board_repo: str) -> str:
    return (
        f"1. Install the skill for your AI agent: `npx skills add {TOOL_REPO} -g -a claude-code -y`\n"
        f"2. Ask your agent: \"set up coop (my board is `{board_repo}`) and tell me if there's an issue I can help with\"\n\n"
        f"Or by hand: `uv tool install git+https://github.com/{TOOL_REPO}` then `coop init {board_repo}` (this also accepts your invitation)."
    )


def invite_message(board_repo: str, user: str) -> str:
    return f"Hi @{user}! I invited you to our coop board ({board_repo}), where friends share GitHub issues to fix with spare AI tokens. To join:\n\n{join_steps(board_repo)}"


def board_readme(board_repo: str, repos: list[dict[str, Any]] | tuple = ()) -> str:
    """Board README: table of registered repos (generated) + how to join."""
    rows = "\n".join(
        f"| [{r['repo']}](https://github.com/{r['repo']}) | "
        f"[open issues](https://github.com/{r['repo']}/issues?q=is%3Aissue+is%3Aopen+label%3A{LABEL_HELP}) | "
        f"{int(r.get('default_budget', 100_000)) // 1000}k |"
        for r in repos
    )
    return (
        f"# coop board\n\nRepos in this group where friends can help with AI tokens ([coop](https://github.com/{TOOL_REPO})).\n\n"
        "| Repo | Help wanted | Default budget |\n|---|---|---|\n" + (rows + "\n" if rows else "") + "\n"
        f"## Join this board\n\nYou need an invitation from the board owner (`coop invite <your-github-username>`). Then:\n\n{join_steps(board_repo)}\n\n"
        "<sub>The table is generated by `coop register` / `coop unregister`; edit `repos.toml`, not this file.</sub>\n"
    )


def _put_readme(board_repo: str, repos: list[dict[str, Any]], message: str) -> None:
    sha = run_gh(["api", f"repos/{board_repo}/contents/README.md", "--jq", ".sha"], check=False)
    content = base64.b64encode(board_readme(board_repo, repos).encode()).decode("ascii")
    args = ["api", "-X", "PUT", f"repos/{board_repo}/contents/README.md", "-f", f"message={message}", "-f", f"content={content}"]
    run_gh(args + (["-f", f"sha={sha}"] if sha else []))


def write_board_readme(board_repo: str) -> None:
    data, _ = fetch_board_manifest(board_repo)
    _put_readme(board_repo, data.get("repos", []), "coop: update README")


def _put_manifest(board_repo: str, data: dict[str, Any], sha: str | None, message: str) -> None:
    content = base64.b64encode(tomli_w.dumps(data).encode()).decode("ascii")
    args = ["api", "-X", "PUT", f"repos/{board_repo}/contents/repos.toml", "-f", f"message={message}", "-f", f"content={content}"]
    if sha:
        args += ["-f", f"sha={sha}"]
    run_gh(args)


def _update_readme(board_repo: str, data: dict[str, Any]) -> None:
    """Best-effort: a README failure must not fail the register."""
    try:
        _put_readme(board_repo, data.get("repos", []), "coop: update README")
    except GhError:
        pass


def _edit_manifest(board_repo: str, message: str, mutate: Callable[[dict[str, Any]], bool]) -> bool:
    """Read-modify-write with retries (concurrent edits make GitHub reject a stale sha)."""
    for attempt in range(3):
        data, sha = fetch_board_manifest(board_repo)
        data.setdefault("repos", [])
        if not mutate(data):
            return False
        try:
            _put_manifest(board_repo, data, sha, message)
            _update_readme(board_repo, data)
            return True
        except GhError:
            if attempt == 2:
                raise
    return False


def create_board(board_repo: str, public: bool = False) -> None:
    run_gh(["repo", "create", board_repo, "--public" if public else "--private", "--add-readme", "--description", "coop board: repos friends can help on"])
    _put_manifest(board_repo, {"repos": []}, None, "coop: init board")
    write_board_readme(board_repo)
    _update_readme(board_repo, {"repos": []})


def list_registered_repos(board_repo: str) -> list[BoardRepoEntry]:
    data, _ = fetch_board_manifest(board_repo)
    return [BoardRepoEntry(r["repo"], int(r.get("default_budget", 100_000))) for r in data.get("repos", [])]


def ensure_repo_labels(repo: str, only: tuple[str, ...] | None = None) -> None:
    for name, color, desc in LABELS:
        if only and name not in only:
            continue
        run_gh(["label", "create", name, "--repo", repo, "--color", color, "--description", desc, "--force"], check=False)


def register_repo_on_board(board_repo: str, target_repo: str, default_budget: int = 100_000) -> str:
    # Only repos you can write to may be registered: coop contributors need the same access.
    if not has_push_access(target_repo):
        raise GhError(f"You need write access to {target_repo} to register it.")
    if not has_push_access(board_repo):
        raise GhError(f"You can read {board_repo} but not edit it. Ask the board owner to run: coop invite {current_github_user()}")
    ensure_repo_labels(target_repo)

    def mutate(data: dict[str, Any]) -> bool:
        for e in data["repos"]:
            if e["repo"].lower() == target_repo.lower():
                e["default_budget"] = default_budget
                return True
        data["repos"].append({"repo": target_repo, "default_budget": default_budget})
        return True

    _edit_manifest(board_repo, f"coop: register {target_repo}", mutate)
    return f"Registered {target_repo} (default budget {default_budget:,}) in {board_repo}."


def unregister_repo_from_board(board_repo: str, target_repo: str) -> str:
    def mutate(data: dict[str, Any]) -> bool:
        kept = [r for r in data["repos"] if r["repo"].lower() != target_repo.lower()]
        changed = len(kept) != len(data["repos"])
        data["repos"] = kept
        return changed

    if _edit_manifest(board_repo, f"coop: unregister {target_repo}", mutate):
        return f"Removed {target_repo} from {board_repo}."
    return f"{target_repo} was not listed in {board_repo}."


def invite_collaborator(repo: str, user: str, permission: str = "push") -> None:
    run_gh(["api", "-X", "PUT", f"repos/{repo}/collaborators/{user}", "-f", f"permission={permission}"])


def has_admin_access(repo: str) -> bool:
    return run_gh(["api", f"repos/{repo}", "--jq", ".permissions.admin"], check=False) == "true"


def repo_collaborators(repo: str) -> list[str]:
    return run_gh(["api", f"repos/{repo}/collaborators", "--paginate", "--jq", ".[].login"]).split()


def repo_invitees(repo: str) -> list[str]:
    """GitHub users with a pending (not yet accepted) invitation to `repo`."""
    return run_gh(["api", f"repos/{repo}/invitations", "--paginate", "--jq", ".[].invitee.login"]).split()


def has_open_coop_issues(repo: str) -> bool:
    raw = run_gh(["api", f"repos/{repo}/issues", "-X", "GET", "-f", f"labels={LABEL_HELP}", "-f", "state=open", "-f", "per_page=100"], check=False)
    return any("pull_request" not in i for i in json.loads(raw or "[]"))


def sync_access(board_repo: str, me: str, only_repo: str | None = None, dry_run: bool = False) -> list[tuple[str, str]]:
    """Invite every member of the board (its collaborators) to repos that have coop-help issues.

    Only repos where you are admin are touched. With `only_repo` that repo is synced even if it
    has no open coop-help issue yet. Returns the (repo, user) invitations sent (or that would be).
    """
    members = [m for m in repo_collaborators(board_repo) if m.lower() != me.lower()]
    repos = [only_repo] if only_repo else [e.repo for e in list_registered_repos(board_repo)]
    sent: list[tuple[str, str]] = []
    for repo in repos:
        if not has_admin_access(repo) or (not only_repo and not has_open_coop_issues(repo)):
            continue
        existing = {c.lower() for c in repo_collaborators(repo)}
        for m in members:
            if m.lower() not in existing:
                if not dry_run:
                    invite_collaborator(repo, m)
                sent.append((repo, m))
    return sent


def pending_invitations() -> list[dict[str, Any]]:
    return json.loads(run_gh(["api", "user/repository_invitations"]) or "[]")


def accept_invitation(invitation_id: int) -> None:
    run_gh(["api", "-X", "PATCH", f"user/repository_invitations/{invitation_id}"])


# ---------------------------------------------------------------- issues


def _to_issue(repo: str, item: dict[str, Any], budget: int) -> CoopIssue:
    labels = [lbl["name"] for lbl in item.get("labels", [])]
    return CoopIssue(
        repo=repo,
        number=item["number"],
        title=item["title"],
        url=item["html_url"],
        body=item.get("body") or "",
        labels=labels,
        assignees=[a["login"] for a in item.get("assignees", [])],
        author=item["user"]["login"],
        default_budget=issue_budget(labels, budget),
    )


def fetch_open_coop_issues(board_repo: str, include_claimed: bool = False) -> list[CoopIssue]:
    """One API call per registered repo (the search API caps queries at 256 chars)."""
    issues: list[CoopIssue] = []
    for e in list_registered_repos(board_repo):
        try:
            raw = run_gh(
                ["api", f"repos/{e.repo}/issues", "-X", "GET", "-f", f"labels={LABEL_HELP}", "-f", "state=open", "-f", "per_page=100"]
            )
        except GhError as err:
            print(f"warning: skipping {e.repo}: {err}", file=sys.stderr)
            continue
        for item in json.loads(raw):
            if "pull_request" in item:
                continue
            issue = _to_issue(e.repo, item, e.default_budget)
            if not include_claimed and (LABEL_CLAIMED in issue.labels or issue.assignees):
                continue
            issues.append(issue)
    return issues


def select_auto_issue(
    issues: list[CoopIssue],
    current_user: str,
    max_tokens: int,
    trust_of: Callable[[CoopIssue], TrustLevel],
    include_own: bool = False,
) -> CoopIssue | None:
    candidates = [i for i in issues if include_own or i.repo.split("/")[0].lower() != current_user.lower()]
    if not candidates:
        return None

    def score(i: CoopIssue) -> tuple[int, int, int]:
        fits = 1 if i.default_budget <= max_tokens else 0
        size = max((SIZE_WEIGHTS.get(lbl, 10) for lbl in i.labels), default=10)
        return (fits, size + {"trusted": 3, "verified": 2, "safe": 1}[trust_of(i)], -i.number)

    return max(candidates, key=score)


def parse_issue_ref(issue_ref: str, fallback_repo: str | None = None) -> tuple[str, int]:
    m = ISSUE_URL_RE.search(issue_ref)
    if m:
        return m.group(1), int(m.group(2))
    if "#" in issue_ref:
        repo, num = issue_ref.split("#", 1)
        return repo, int(num)
    if issue_ref.isdigit() and fallback_repo:
        return fallback_repo, int(issue_ref)
    raise ValueError(f"Cannot parse issue reference: {issue_ref}")


def fetch_single_issue(repo: str, number: int, default_budget: int = 100_000) -> CoopIssue:
    return _to_issue(repo, json.loads(run_gh(["api", f"repos/{repo}/issues/{number}"])), default_budget)


def claim_issue(repo: str, number: int, me: str) -> bool:
    """Refuse issues that are already claimed or assigned to someone else. Otherwise assign + label,
    then re-read: if someone claimed at the very same moment, the alphabetically first assignee
    wins and the loser backs off. GitHub has no assignment lock, so this is best effort: anyone
    with write access (e.g. the repo owner) can still change assignees by hand."""
    if not has_push_access(repo):
        raise GhError(f"You need write access to {repo} to claim issues (ask the owner: `coop invite {me} {repo}`).")
    current = fetch_single_issue(repo, number)
    taken = LABEL_CLAIMED in current.labels or any(a.lower() != me.lower() for a in current.assignees)
    if taken:
        return False  # already someone's: never take it over
    ensure_repo_labels(repo, only=(LABEL_CLAIMED,))
    run_gh(["issue", "edit", str(number), "--repo", repo, "--add-assignee", "@me", "--add-label", LABEL_CLAIMED])
    assignees = sorted(a.lower() for a in fetch_single_issue(repo, number).assignees)
    if assignees and assignees[0] != me.lower():
        run_gh(["issue", "edit", str(number), "--repo", repo, "--remove-assignee", "@me"], check=False)
        return False
    return True


def flag_issue(repo: str, number: int, size: str | None = None, budget: int | None = None) -> list[str]:
    ensure_repo_labels(repo)
    labels = [LABEL_HELP]
    if size:
        labels.append(f"size:{size}")
    if budget:
        label = f"budget:{budget // 1000}k" if budget % 1000 == 0 else f"budget:{budget}"
        labels.append(label)
        run_gh(["label", "create", label, "--repo", repo, "--color", "BFD4F2", "--force"], check=False)
    run_gh(["issue", "edit", str(number), "--repo", repo, "--add-label", ",".join(labels)])
    return labels


def release_issue(repo: str, number: int) -> None:
    run_gh(["issue", "edit", str(number), "--repo", repo, "--remove-assignee", "@me", "--remove-label", LABEL_CLAIMED], check=False)
